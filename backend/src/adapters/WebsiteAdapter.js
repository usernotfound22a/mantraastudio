/**
 * Website chat widget adapter.
 *
 * The odd one out: there is NO third-party API. The widget talks to our own
 * /api/widget endpoints, so "sending" a message is a database write and
 * "receiving" is a poll.
 *
 * It still implements the full adapter contract, which is the proof that the
 * abstraction is real: the inbox, the AI service and the analytics do not know
 * or care that website messages never touch an external API.
 *
 * If SocialHub's public site went down, only this adapter's transport would
 * change - every other part of the system would be untouched.
 *
 * Channel config (channels.config JSON):
 *   { widgetKey, greeting, themeColor, defaultName, allowedDomains, companyName }
 */
import crypto from 'node:crypto';
import { BaseAdapter } from './BaseAdapter.js';
import { childLogger } from '../config/logger.js';
import { AppError } from '../middleware/error.js';

const log = childLogger('adapter:website');

export class WebsiteAdapter extends BaseAdapter {
  static type = 'website';
  static label = 'Website Chat';
  static description = 'Embed the SocialHub chat bubble on your own website.';
  // Our own first-party endpoint - no third party signs it.
  static requiresSignature = false;

  static capabilities = {
    attachments: true,
    readReceipts: true,
    typingIndicator: false,
    // A visitor who never opened a tab cannot be messaged, so no proactive
    // outreach from the inbox.
    proactiveMessaging: false,
    mediaUpload: true,
  };

  // ---------------------------------------------------------------------
  // Internals
  // ---------------------------------------------------------------------

  /** Public identity of this widget instance, safe to hand to the browser. */
  get widgetKey() {
    return this.config.widgetKey;
  }

  // ---------------------------------------------------------------------
  // REQUIRED contract
  // ---------------------------------------------------------------------

  /**
   * The widget posts its own normalised envelope:
   *   {
   *     visitorId, name, email, message, attachments, pageUrl, referrer
   *   }
   *
   * The visitor id is generated by the widget on first load and stored in
   * localStorage, so it is the website equivalent of a PSID.
   */
  parseInbound(payload) {
    if (!payload?.message || String(payload.message).trim() === '') return [];

    // A conversation is keyed by visitorId: one thread per browser profile.
    const visitorId = payload.visitorId || `anon_${hash(payload.pageUrl ?? '')}`;

    return [
      {
        // No remote ids exist, so we mint a stable local one.
        externalMessageId: payload.messageId ?? `wp_${crypto.randomUUID()}`,
        conversationExternalId: visitorId,
        contact: this.normalizeContact({
          visitorId,
          name: payload.name,
          email: payload.email,
          locale: payload.locale,
        }),
        content: {
          text: String(payload.message).slice(0, 4000),
          attachments: this.normalizeAttachments(payload.attachments),
          quickReplies: [],
          postbackPayload: null,
        },
        timestamp: payload.timestamp ? new Date(payload.timestamp) : new Date(),
        metadata: {
          channel: 'website',
          pageUrl: payload.pageUrl ?? null,
          referrer: payload.referrer ?? null,
          userAgent: payload.userAgent ?? null,
        },
      },
    ];
  }

  /**
   * The website widget authenticates with its own `widgetKey` instead of a
   * Meta signature, so there is no account id to resolve.
   */
  resolveAccountId() {
    return null;
  }

  normalizeContact(raw) {
    return {
      externalId: raw?.visitorId ?? null,
      // Until the visitor fills in the pre-chat form we show the channel name
      // in the UI rather than a bare id.
      name: raw?.name?.trim() || this.config.defaultName || 'Website visitor',
      avatarUrl: null,
      email: raw?.email?.trim() || null,
      locale: raw?.locale ?? null,
    };
  }

  /**
   * "Delivering" a website message is a no-op: `sendMessageToConversation()`
   * has ALREADY persisted the row, and the widget polls for it.
   *
   * This is the honest implementation of the contract for a first-party
   * channel, and it is why the inbox code never needs an
   * `if (channel === 'website')` branch.
   */
  async sendMessage({ persistedMessage, body, attachments = [] }) {
    if (!body && attachments.length === 0) {
      throw new Error('sendMessage() needs a body or an attachment');
    }
    if (!persistedMessage?.id) {
      throw new Error('WebsiteAdapter expects the conversation service to persist the message first');
    }

    return {
      externalId: String(persistedMessage.id),
      status: 'sent',
      raw: { deliveredInApp: true, transport: 'database' },
    };
  }

  // ---------------------------------------------------------------------
  // Optional capabilities
  // ---------------------------------------------------------------------

  /**
   * There is no signature to check, but we DO apply a light allow-list so the
   * endpoint cannot be abused from any website on the internet.
   */
  verifyWebhook({ headers = {} }) {
    const origin = headers.origin ?? headers.referer ?? null;
    const allowed = this.config.allowedDomains ?? [];

    if (allowed.length > 0 && origin) {
      const hostname = safeHostname(origin);
      const permitted = allowed.some(
        (domain) => hostname === domain || hostname?.endsWith(`.${domain}`),
      );
      if (!permitted) {
        throw AppError.forbidden(`Origin ${hostname} is not allowed to use this widget`);
      }
    }

    return { kind: 'widget', verified: true, origin };
  }

  /** Widget calls this when the visitor opens/scrolls to the thread. */
  async markAsRead() {
    // Read state is tracked in our database via messages.read_at, not remotely.
    return { supported: true, local: true };
  }

  async healthCheck() {
    if (!this.widgetKey) {
      return { ok: false, message: 'No widget key generated - reconnect the channel' };
    }
    return { ok: true, message: 'Widget ready to embed' };
  }

  describe() {
    return {
      ...super.describe(),
      /** The <script> snippet the settings screen renders for the user. */
      embedSnippet: this.embedSnippet(),
    };
  }

  /**
   * Ready-to-paste embed code.
   *
   * The widget is a single self-contained file, so there is no separate
   * `loader.js` to fetch first - one tag is the whole integration. It must
   * match the snippet the dashboard renders, otherwise a customer copy-pasting
   * from the API response gets a different result to the one in the UI.
   */
  embedSnippet(apiBaseUrl = '') {
    const base = apiBaseUrl || process.env.PUBLIC_API_URL || 'http://localhost:4000';
    const key = this.widgetKey ?? '';
    if (!key) {
      throw AppError.badRequest(
        'This website channel has no widget key yet. Rotate the key in Settings, then copy the snippet.',
      );
    }
    return `<script src="${base}/widget/socialhub.js" data-key="${key}" async></script>`;
  }
}

/** Short deterministic hash, used only to group anonymous visitors. */
function hash(value) {
  return crypto.createHash('sha1').update(String(value)).digest('hex').slice(0, 12);
}

/** Extracts a hostname from an origin/referer URL without throwing. */
function safeHostname(value) {
  try {
    return new URL(value).hostname;
  } catch {
    return null;
  }
}

export default WebsiteAdapter;
