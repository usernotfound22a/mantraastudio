--     One row per message (the UNIQUE key powers the upsert in the route).
-- ===========================================================================
CREATE TABLE IF NOT EXISTS "message_feedback" (
  "id"              BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "message_id"      BIGINT NOT NULL,
  "conversation_id" BIGINT NOT NULL,
  "workspace_id"    BIGINT NOT NULL,
  "user_id"         BIGINT NULL,
  "rating"          TEXT NOT NULL,
  "comment"         VARCHAR(500)    NULL,
  "created_at"      TIMESTAMPTZ       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at"      TIMESTAMPTZ       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_feedback_message" UNIQUE ("message_id"),
  CONSTRAINT "fk_feedback_message" FOREIGN KEY ("message_id") REFERENCES "messages" ("id")  ON DELETE CASCADE,
  CONSTRAINT "fk_feedback_conversation" FOREIGN KEY ("conversation_id") REFERENCES "conversations" ("id")  ON DELETE CASCADE,
  CONSTRAINT "fk_feedback_workspace" FOREIGN KEY ("workspace_id") REFERENCES "workspaces" ("id")  ON DELETE CASCADE,
  CONSTRAINT "fk_feedback_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id")  ON DELETE SET NULL
);
-- ===========================================================================
--  10. unanswered_questions  -  what the AI could NOT answer.
--
--      This is the most useful table in the project for the report: it is the
--      evidence that drives "add this to your knowledge base" and shows the
--      assistant's real coverage. Keyed on the question text so the same
--      question asked 40 times is one row with occurrences = 40.
-- ===========================================================================
CREATE TABLE IF NOT EXISTS "unanswered_questions" (
  "id"              BIGINT GENERATED BY DEFAULT AS IDENTITY,
  "workspace_id"    BIGINT NOT NULL,
  "question"        VARCHAR(500)    NOT NULL,
  "conversation_id" BIGINT NULL,
  "channel_id"      BIGINT NULL,
  "occurrences"     INTEGER    NOT NULL DEFAULT 1,
  "first_asked_at"  TIMESTAMPTZ       NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "last_asked_at"   TIMESTAMPTZ        NOT NULL,
  PRIMARY KEY ("id"),
  -- The same question must not create a second row.
  CONSTRAINT "uq_unanswered" UNIQUE ("workspace_id", "question"),
  CONSTRAINT "fk_unanswered_workspace" FOREIGN KEY ("workspace_id") REFERENCES "workspaces" ("id")  ON DELETE CASCADE,
  CONSTRAINT "fk_unanswered_conversation" FOREIGN KEY ("conversation_id") REFERENCES "conversations" ("id")  ON DELETE SET NULL
);
